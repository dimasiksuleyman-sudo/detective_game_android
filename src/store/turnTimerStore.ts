/**
 * Режим блиц: сколько времени текущего хода уже прошло. Живёт в памяти, чтобы
 * отсчёт не начинался заново при переходах между экранами хода. После полного
 * перезапуска приложения отсчёт хода начинается сначала (ADR-034).
 */
import { create } from 'zustand';
export const useTurnTimer = create<{ key: string; elapsedMs: number }>(() => ({
  key: '',
  elapsedMs: 0,
}));
